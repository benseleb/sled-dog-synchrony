#!/usr/bin/env python3
"""Result tables as markdown -> docs/RESULTS.md (run after steps 0-6).
Every number quoted in the README and docs comes from here.

Usage: summarize.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd

from synchrony import config
from synchrony.datasets import ANALYSED_DOGS, QUEUE, RUN, SPEED_MIN
from synchrony.windows import windows_for

PRIMARY_RUN = "DEC_11_TEST"
OUT = config.REPO / "docs" / "RESULTS.md"
LABEL = {"DEC_11_TEST": "Dec 11", "DEC_10_TEST/Run1": "Dec 10, run 1", "DEC_10_TEST/Run2": "Dec 10, run 2",
         "DEC_05_TEST": "Dec 5", "DEC_07_TEST": "Dec 7", "DEC_09_TEST": "Dec 9",
         "NOV_23_TEST": "Nov 23", "NOV_29_TEST": "Nov 29"}


def md_table(df, floatfmt=".2f"):
    """Plain markdown table (no tabulate dependency); numbers right-aligned."""
    def cell(v):
        if isinstance(v, float):
            return "" if pd.isna(v) else format(v, floatfmt)
        return str(v)
    num = [pd.api.types.is_numeric_dtype(df[c]) for c in df.columns]
    lines = ["| " + " | ".join(map(str, df.columns)) + " |",
             "|" + "|".join("---:" if n else "---" for n in num) + "|"]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def pct(df):
    return 100 * df.n_significant.sum() / df.n_windows.sum()


def main():
    force = pd.read_csv(config.ANALYSIS_DIR / "force_phase_regression.csv")
    plv = pd.read_csv(config.ANALYSIS_DIR / "pairwise_plv.csv")
    boot = pd.read_csv(config.SYNC_DIR / "sync_check_boot_segments.csv")
    table1 = pd.read_csv(config.TABLES_DIR / "table1.csv")

    fitted = force.dropna(subset=["beta_omega"]).copy()
    fitted["hand_check"] = fitted.hand_check.astype(bool)
    clean = fitted[~fitted.hand_check]
    flagged = set(zip(fitted[fitted.hand_check].day, fitted[fitted.hand_check].dog))
    plv["has_flagged"] = [(d, a) in flagged or (d, b) in flagged for d, a, b in zip(plv.day, plv.dog_a, plv.dog_b)]
    indep = plv[plv.day != PRIMARY_RUN]

    s = ["# Results", "",
         "Generated by `scripts/summarize.py` from `results/`. Do not edit by hand.", ""]

    # ---- data
    minutes = sum(windows_for(day).duration_s.sum() for day in ANALYSED_DOGS) / 60
    s += ["## Data", "",
          f"{len(ANALYSED_DOGS)} runs, {len({d for _, d, _, _ in QUEUE})} dogs, {len(QUEUE)} dog-runs, "
          f"{minutes:.0f} min of qualifying windows (≥ 2 dogs recording, ≥ 120 s, team reaches {SPEED_MIN:g} m/s).", ""]
    rows = []
    for day in ANALYSED_DOGS:
        w = windows_for(day)
        b = boot[boot.day == day]
        rows.append({"Run": LABEL[day], "Sync tier": RUN[day].tier, "Dogs": len(ANALYSED_DOGS[day]),
                     "Windows": len(w), "Minutes": round(w.duration_s.sum() / 60),
                     "Boot segments in sync": int((b.verdict == "in sync").sum()),
                     "can't tell": int((b.verdict == "can't tell").sum()),
                     "offset": int(b.verdict.str.startswith("OFFSET").sum()),
                     "Force fits": int((fitted.day == day).sum())})
    s += [md_table(pd.DataFrame(rows)), ""]

    # ---- Table I
    t1 = table1.rename(columns={"dog": "Dog", "n_strides": "Strides", "r2_model": "R²", "beta0": "β₀",
                                "beta_cos": "β_cos", "beta_sin": "β_sin", "beta_F": "β_F",
                                "beta_omega": "β_ω", "A_phi": "A_φ", "theta0": "θ₀"})
    s += ["## Table I: force–phase regression, Dec 11 primary window", "",
          "Hand-curated stride boundaries, 766 s window, Huber regression of Δω_k on cos φ_Fk, sin φ_Fk, "
          "F_k and ω_{k−1} (F and ω z-scored per dog). A_φ = √(β_cos² + β_sin²), θ₀ = atan2(β_sin, β_cos).", "",
          md_table(t1[["Dog", "Strides", "R²", "β₀", "β_cos", "β_sin", "β_F", "β_ω", "A_φ", "θ₀"]], ".3f"), ""]

    # ---- force regression, all runs
    s += ["## Force–phase regression, all runs", "",
          f"{len(fitted)} dog-runs fitted (automatic segmentation, hand-corrected where available). "
          f"{len(flagged)} are flagged for hand correction (β_ω outside [−0.77, −0.33]) and excluded from the ranges. "
          f"β_F > 0 in {(fitted.beta_F > 0).sum()} of {len(fitted)} fits.", ""]
    rng = clean.groupby("day", sort=False).agg(dogs=("dog", "size"), r2_lo=("r2_model", "min"), r2_hi=("r2_model", "max"),
                                               bw_lo=("beta_omega", "min"), bw_hi=("beta_omega", "max"),
                                               bf_lo=("beta_F", "min"), bf_hi=("beta_F", "max"),
                                               a_lo=("A_phi", "min"), a_hi=("A_phi", "max")).reset_index()
    fmt = lambda lo, hi: f"{lo:.2f} to {hi:.2f}"
    s += [md_table(pd.DataFrame({"Run": rng.day.map(LABEL), "Unflagged dogs": rng.dogs,
                                 "R²": [fmt(a, b) for a, b in zip(rng.r2_lo, rng.r2_hi)],
                                 "β_ω": [fmt(a, b) for a, b in zip(rng.bw_lo, rng.bw_hi)],
                                 "β_F": [fmt(a, b) for a, b in zip(rng.bf_lo, rng.bf_hi)],
                                 "A_φ": [fmt(a, b) for a, b in zip(rng.a_lo, rng.a_hi)]})), "",
          f"All unflagged: R² {fmt(clean.r2_model.min(), clean.r2_model.max())}, "
          f"β_ω {fmt(clean.beta_omega.min(), clean.beta_omega.max())}.", "",
          "<details><summary>Every dog-run</summary>", ""]
    per = force.copy()
    per["Run"] = per.day.map(LABEL)
    per["Flag"] = ["hand-check" if h is True or h == "True" else "" for h in per.hand_check]
    per["Note"] = per.get("note", pd.Series("", index=per.index)).fillna("")
    per = per.rename(columns={"dog": "Dog", "zc_source": "Crossings", "n_strides": "Strides", "r2_model": "R²",
                              "beta_F": "β_F", "beta_omega": "β_ω", "A_phi": "A_φ", "theta0": "θ₀"})
    s += [md_table(per[["Run", "Dog", "Crossings", "Strides", "R²", "β_F", "β_ω", "A_φ", "θ₀", "Flag", "Note"]]
                   .astype({"Strides": "Int64"})), "", "</details>", ""]

    # ---- PLV
    rows = []
    for day, g in plv.groupby("day", sort=False):
        rows.append({"Run": LABEL[day], "Verified dogs": len(set(g.dog_a) | set(g.dog_b)), "Pairs": len(g),
                     "60 s windows tested": int(g.n_windows.sum()), "Significant": int(g.n_significant.sum()),
                     "%": round(pct(g), 2)})
    for label, g in [("**All runs**", plv), ("Independent of Dec 11", indep),
                     ("Excluding flagged dogs", plv[~plv.has_flagged]),
                     ("Independent, excluding flagged", indep[~indep.has_flagged])]:
        rows.append({"Run": label, "Verified dogs": "", "Pairs": len(g), "60 s windows tested": int(g.n_windows.sum()),
                     "Significant": int(g.n_significant.sum()), "%": round(pct(g), 2)})
    s += ["## Pairwise phase locking", "",
          "Verified clocks only. 60 s windows, 15 s step, phases masked below 3 m/s, windows < 90% valid not tested; "
          "significant if PLV > 95th percentile of a pooled 800-shift surrogate null and PLV > 0.70. "
          "Pairs count once per window they share. Dec 5, Dec 9 and Dec 10 run 2 have no two verified dogs "
          "in the same window.", "",
          md_table(pd.DataFrame(rows)), ""]
    top = (plv.groupby(["day", "dog_a", "dog_b"], sort=False)
              .agg(sig=("n_significant", "sum"), win=("n_windows", "sum"), flag=("has_flagged", "first"))
              .reset_index().query("sig > 0").sort_values("sig", ascending=False))
    s += ["### Pairs with any significant window", "",
          "Summed over the run's windows. * = involves a dog flagged for hand correction.", "",
          md_table(pd.DataFrame({"Run": top.day.map(LABEL),
                                 "Pair": [f"{a}–{b}{' *' if f else ''}" for a, b, f in zip(top.dog_a, top.dog_b, top.flag)],
                                 "Significant": top.sig, "Windows tested": top.win})), ""]

    OUT.write_text("\n".join(s))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
